'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const {once}=require('node:events');
const {mkdtemp,rm}=require('node:fs/promises');
const {tmpdir}=require('node:os');
const {join}=require('node:path');
const {createServer}=require('../server');
test('MVW Trust serves an accessible branded shell and its artwork locally',async t=>{
  const dir=await mkdtemp(join(tmpdir(),'trust-brand-test-'));
  const server=createServer({dataFile:join(dir,'state.json')});
  server.listen(0,'127.0.0.1');await once(server,'listening');
  t.after(async()=>{await new Promise(resolve=>server.close(resolve));await rm(dir,{recursive:true,force:true})});
  const url='http://127.0.0.1:'+server.address().port;
  const r=await fetch(url),html=await r.text();
  assert.match(html,/<title>MVW Trust \| Privacy Operations<\/title>/);
  assert.match(html,/Not an official Marriott Vacations Worldwide service/);
  assert.match(html,/aria-controls="work-tabs"/);
  assert.match(html,/id="glass-toggle"[^>]*aria-pressed="false"/);
  assert.match(html,/id="workspace-metrics"/);
  assert.doesNotMatch(html,/(?:href|src)="https?:/i);
  const css=await (await fetch(url+'/styles.css')).text();
  assert.match(css,/backdrop-filter:blur/);
  assert.match(css,/prefers-reduced-transparency:reduce/);
  assert.match(css,/prefers-reduced-motion:reduce/);
  const art=await fetch(url+'/mvw-horizon.svg');
  assert.match(art.headers.get('content-type'),/^image\/svg\+xml/);
  assert.match(await art.text(),/<svg /);
});
